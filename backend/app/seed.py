def seed_foods() -> int:
    """foods 表为空时写入内置数据，返回写入条数；非空时返回 0（幂等）。"""
    exists = db.session.execute(select(func.count()).select_from(Food)).scalar_one()
    if exists:
        return 0
    for (name, aliases, category, unit, portion, kcal, protein, fat,
         carbs, fiber, sodium, barcode, brand) in SEED_FOODS:
        db.session.add(Food(
            name=name, aliases=aliases, category=category, unit=unit,
            default_portion_g=portion, calories_kcal_per_100g=kcal,
            protein_g_per_100g=protein, fat_g_per_100g=fat, carbs_g_per_100g=carbs,
            fiber_g_per_100g=fiber, sodium_mg_per_100g=sodium,
            barcode=barcode, brand=brand, source="builtin",
        ))
    db.session.commit()
    return len(SEED_FOODS)


